# 側邊欄說明
def show_sidebar_help():
    """在側邊欄顯示說明連結"""
    import streamlit as st
    
    with st.sidebar:
        st.divider()
        with st.expander("📚 系統說明"):
            tabs = st.tabs(["指標", "評分", "策略"])
            with tabs[0]:
                st.markdown(INDICATOR_HELP)
            with tabs[1]:
                st.markdown(SCORING_HELP)
            with tabs[2]:
                st.markdown(STRATEGY_HELP)
